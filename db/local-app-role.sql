DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'taimei_app') THEN
    CREATE ROLE taimei_app LOGIN PASSWORD 'taimei_app';
  END IF;
END $$;
GRANT USAGE ON SCHEMA public TO taimei_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO taimei_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO taimei_app;
